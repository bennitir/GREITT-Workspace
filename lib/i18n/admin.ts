export function adminText(language: string | null | undefined) {
  return text[normalizeUiLanguage(language)];
}

export function adminLocale(language: string | null | undefined) {
  const lang: UiLanguage = normalizeUiLanguage(language);
  return lang === "is" ? "is-IS" : lang === "en" ? "en-GB" : lang === "pl" ? "pl-PL" : "sr-RS";
}

export function adminRoleLabel(role: string, language: string | null | undefined) {
  const roles = adminText(language).roles as Record<string, string>;
  return roles[role] ?? role;
}

export function adminModuleLabel(moduleId: string, fallback: string, language: string | null | undefined) {
  const modules = adminText(language).modules as Record<string, string>;
  return modules[moduleId] ?? fallback;
}
