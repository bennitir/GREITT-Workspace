export function inventoryText(language: string | null | undefined) {
  return text[normalizeUiLanguage(language)];
}

export function inventoryLocale(language: string | null | undefined) {
  return localeByLanguage[normalizeUiLanguage(language)];
}

export function inventoryFormatNumber(value: number, language: string | null | undefined, maximumFractionDigits = 3) {
  return new Intl.NumberFormat(inventoryLocale(language), {
    maximumFractionDigits,
  }).format(value);
}

export function inventoryFormatMoney(value: number | null | undefined, language: string | null | undefined) {
  if (value === null || value === undefined || !Number.isFinite(value)) return "—";
  return `${new Intl.NumberFormat(inventoryLocale(language), { maximumFractionDigits: 2 }).format(value)} kr.`;
}

export function inventoryFormatDate(value: Date | string, language: string | null | undefined) {
  const date = value instanceof Date ? value : new Date(value);
  return new Intl.DateTimeFormat(inventoryLocale(language), {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  }).format(date);
}

export function inventoryLocationKindText(value: string, language: string | null | undefined) {
  const t = inventoryText(language);
  if (value === "WAREHOUSE") return t.warehouse;
  if (value === "STORE") return t.store;
  if (value === "STAGING") return t.staging;
  if (value === "VEHICLE") return t.vehicle;
  if (value === "SITE") return t.site;
  if (value === "TRANSIT") return t.transit;
  return t.other;
}

export function inventoryCommitmentTypeText(value: string, language: string | null | undefined) {
  const t = inventoryText(language);
  if (value === "RESERVATION") return t.reservation;
  if (value === "SALE_PENDING") return t.salePending;
  return t.otherCommitment;
}

export function inventoryMovementTypeText(value: string, language: string | null | undefined) {
  const t = inventoryText(language);
  if (value === "OPENING") return t.opening;
  if (value === "ADJUSTMENT_IN") return t.adjustmentIn;
  if (value === "ADJUSTMENT_OUT") return t.adjustmentOut;
  if (value === "WORK_USAGE") return t.workUsage;
  if (value === "RECEIPT") return t.receipt;
  if (value === "ISSUE") return t.issue;
  if (value === "RETURN") return t.returnMovement;
  if (value === "STOCKTAKE_ADJUSTMENT") return t.stocktakeAdjustment;
  if (value === "WASTE") return t.wasteMovement;
  if (value === "TRACKING_ADJUSTMENT") return t.trackingAdjustment;
  if (value === "TRANSFER_OUT") return t.transferOut;
  if (value === "TRANSFER_IN") return t.transferIn;
  return value;
}

export function inventoryReasonText(value: string | null | undefined, language: string | null | undefined) {
  if (!value) return "—";
  const t = inventoryText(language);
  if (value === "COUNT_VARIANCE") return t.countVariance;
  if (value === "SHRINKAGE") return t.shrinkage;
  if (value === "DAMAGE") return t.damage;
  if (value === "SPOILAGE") return t.spoilage;
  if (value === "THEFT") return t.theft;
  if (value === "OBSOLETE") return t.obsolete;
  if (value === "OTHER") return t.otherReason;
  if (value === "STOCK_TRACKING_DISABLED") return t.stockTrackingDisabledReason;
  return value;
}
