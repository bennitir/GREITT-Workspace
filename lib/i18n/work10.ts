export function work10FormatDuration(totalMinutes: number, language: string | null | undefined) {
  const t = work10Text(language);
  const safeMinutes = Number.isFinite(totalMinutes) ? Math.max(0, Math.trunc(totalMinutes)) : 0;
  const hours = Math.floor(safeMinutes / 60);
  const minutes = safeMinutes % 60;

  if (hours > 0 && minutes > 0) return `${hours} ${t.hoursShort} ${minutes} ${t.minutesShort}`;
  if (hours > 0) return `${hours} ${t.hoursShort}`;
  return `${minutes} ${t.minutesShort}`;
}

