export function stocktakeMobileText(language: string | null | undefined) {
  const normalized: UiLanguage = normalizeUiLanguage(language ?? "is");
  return text[normalized];
}

export function stocktakeSessionStatusText(status: string, language: string | null | undefined) {
  const t = stocktakeMobileText(language);
  if (status === "COUNTING") return t.statusCounting;
  if (status === "REVIEW") return t.statusReview;
  if (status === "COMPLETED") return t.statusCompleted;
  if (status === "CANCELLED") return t.statusCancelled;
  return status;
}
